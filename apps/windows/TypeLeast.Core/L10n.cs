using System.Globalization;
using System.Text.RegularExpressions;

namespace TypeLeast.Core;

/// <summary>UI language stays fixed until restart. User content is never used as a lookup key.</summary>
public static class L10n
{
    public static readonly string[] Choices = { "system", "zh-Hans", "en" };
    public static string Normalize(string? value) => Choices.Contains(value ?? "") ? value! : "system";
    public static string Resolve(string? value, string? systemLanguage = null)
    {
        var choice = Normalize(value);
        return choice != "system" ? choice : (systemLanguage ?? CultureInfo.CurrentUICulture.Name)
            .StartsWith("zh", StringComparison.OrdinalIgnoreCase) ? "zh-Hans" : "en";
    }
    public static string Language { get; private set; } = Resolve("system");
    public static CultureInfo Culture => CultureInfo.GetCultureInfo(Language == "en" ? "en-US" : "zh-CN");
    public static void Configure(string? preference)
    {
        Language = Resolve(preference);
        CultureInfo.CurrentCulture = Culture;
        CultureInfo.CurrentUICulture = Culture;
        CultureInfo.DefaultThreadCurrentCulture = Culture;
        CultureInfo.DefaultThreadCurrentUICulture = Culture;
    }
    public static string T(string key, params object?[] arguments) => Render(key, Language, arguments);
    public static string Render(string key, string language, params object?[] arguments)
    {
        var template = language == "en" && English.TryGetValue(key, out var translated) ? translated : key;
        var culture = CultureInfo.GetCultureInfo(language == "en" ? "en-US" : "zh-CN");
        return Regex.Replace(template, @"\{([0-9]+)\}", m =>
        {
            var index = int.Parse(m.Groups[1].Value, CultureInfo.InvariantCulture);
            return index < arguments.Length ? Convert.ToString(arguments[index], culture) ?? "" : m.Value;
        });
    }
